
import json
from contextlib import contextmanager
from datetime import datetime, timezone
from typing import Any, Iterator

import psycopg
from psycopg.rows import dict_row

from app.core.config import get_settings


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


@contextmanager
def connection() -> Iterator[psycopg.Connection]:
    settings = get_settings()

    conn = psycopg.connect(
        settings.neon_db,
        row_factory=dict_row,
    )

    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def init_db() -> None:
    schema = """
    CREATE TABLE IF NOT EXISTS tickets (
        id TEXT PRIMARY KEY,
        created_at TEXT NOT NULL,
        updated_at TEXT NOT NULL,
        issue_type TEXT NOT NULL,
        department TEXT NOT NULL,
        severity INTEGER NOT NULL,
        status TEXT NOT NULL,
        description TEXT,
        transcript TEXT,
        transcript_language TEXT,
        image_path TEXT,
        audio_path TEXT,
        video_path TEXT,
        latitude DOUBLE PRECISION,
        longitude DOUBLE PRECISION,
        visual_evidence TEXT NOT NULL DEFAULT '[]',
        suggested_severity INTEGER,
        justification TEXT,
        hazards TEXT NOT NULL DEFAULT '[]',
        image_quality TEXT,
        consistency TEXT,
        model_confidence_uncalibrated DOUBLE PRECISION,
        rules_applied TEXT NOT NULL DEFAULT '[]',
        needs_human_review BOOLEAN NOT NULL,
        review_requested BOOLEAN NOT NULL DEFAULT FALSE,
        review_reasons TEXT NOT NULL DEFAULT '[]',
        is_simulated BOOLEAN NOT NULL DEFAULT FALSE,
        vision_provider TEXT,
        vision_model TEXT,
        asr_provider TEXT,
        asr_model TEXT,
        ast_tags TEXT NOT NULL DEFAULT '[]',
        audio_events TEXT NOT NULL DEFAULT 'null',
        audio_timeline TEXT NOT NULL DEFAULT 'null',
        severity_score INTEGER NOT NULL DEFAULT 0,
        severity_factors TEXT NOT NULL DEFAULT '{}',
        text_issue_type TEXT,
        detected_language TEXT,
        location_context TEXT NOT NULL DEFAULT '[]',
        duplicate_cluster_id TEXT,
        duplicate_count INTEGER NOT NULL DEFAULT 1,
        visual_risk_factors TEXT NOT NULL DEFAULT '[]',
        text_analysis TEXT NOT NULL DEFAULT '{}',
        ward_id TEXT,
        ward_name TEXT,
        assigned_officer TEXT,
        assigned_queue TEXT,
        sla_hours DOUBLE PRECISION,
        escalation_path TEXT NOT NULL DEFAULT '[]',
        routing_rule_id INTEGER,
        reporter_label TEXT NOT NULL DEFAULT 'Anonymous',
        reporter_email TEXT,
        reporter_phone TEXT,
        notification_channels TEXT NOT NULL DEFAULT '[]',
        reporter_user_id TEXT
    );

    CREATE TABLE IF NOT EXISTS user_roles (
        user_id TEXT PRIMARY KEY,
        role TEXT NOT NULL CHECK (role IN ('PUBLIC', 'ADMIN')),
        email TEXT,
        name TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TEXT NOT NULL
    );

    ALTER TABLE user_roles ADD COLUMN IF NOT EXISTS email TEXT;
    ALTER TABLE user_roles ADD COLUMN IF NOT EXISTS name TEXT;
    ALTER TABLE user_roles ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT NOW();

    CREATE TABLE IF NOT EXISTS status_history (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ticket_id TEXT NOT NULL REFERENCES tickets(id),
        status TEXT NOT NULL,
        actor TEXT NOT NULL,
        reason TEXT,
        created_at TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS audit_events (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ticket_id TEXT NOT NULL REFERENCES tickets(id),
        field TEXT NOT NULL,
        old_value TEXT,
        new_value TEXT,
        actor TEXT NOT NULL,
        reason TEXT NOT NULL,
        created_at TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS provider_traces (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ticket_id TEXT NOT NULL REFERENCES tickets(id),
        provider TEXT NOT NULL,
        model TEXT NOT NULL,
        task TEXT NOT NULL,
        outcome TEXT NOT NULL,
        latency_ms INTEGER,
        error_code TEXT,
        created_at TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS routing_rules (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        issue_type TEXT,
        ward_id TEXT,
        department TEXT NOT NULL,
        officer TEXT,
        queue TEXT,
        sla_hours DOUBLE PRECISION NOT NULL,
        escalation_path TEXT NOT NULL DEFAULT '[]',
        priority INTEGER NOT NULL DEFAULT 100,
        active BOOLEAN NOT NULL DEFAULT TRUE,
        created_at TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS ticket_comments (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ticket_id TEXT NOT NULL REFERENCES tickets(id),
        author_label TEXT NOT NULL,
        body TEXT NOT NULL,
        created_at TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS ticket_votes (
        ticket_id TEXT NOT NULL REFERENCES tickets(id),
        voter_id TEXT NOT NULL,
        created_at TEXT NOT NULL,
        PRIMARY KEY (ticket_id, voter_id)
    );

    CREATE TABLE IF NOT EXISTS ticket_ratings (
        ticket_id TEXT NOT NULL REFERENCES tickets(id),
        voter_id TEXT NOT NULL,
        rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
        comment TEXT,
        created_at TEXT NOT NULL,
        PRIMARY KEY (ticket_id, voter_id)
    );

    CREATE TABLE IF NOT EXISTS notification_outbox (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ticket_id TEXT NOT NULL REFERENCES tickets(id),
        channel TEXT NOT NULL,
        destination TEXT NOT NULL,
        message TEXT NOT NULL,
        outcome TEXT NOT NULL,
        error_code TEXT,
        created_at TEXT NOT NULL
    );

    CREATE INDEX IF NOT EXISTS idx_tickets_created
        ON tickets(created_at DESC);

    CREATE INDEX IF NOT EXISTS idx_tickets_review
        ON tickets(needs_human_review, created_at DESC);

    CREATE INDEX IF NOT EXISTS idx_tickets_status
        ON tickets(status);
    """

    with connection() as conn:
        # Execute each SQL statement separately.
        for statement in schema.split(";"):
            if statement.strip():
                conn.execute(statement)

        # Read current PostgreSQL schema.
        columns = {
            row["column_name"]
            for row in conn.execute("""
                SELECT column_name
                FROM information_schema.columns
                WHERE table_schema = 'public'
                  AND table_name = 'tickets'
            """).fetchall()
        }
        conn.execute("ALTER TABLE tickets ADD COLUMN IF NOT EXISTS reporter_user_id TEXT")

        # Supports existing PostgreSQL installations with older schemas.
        missing_columns = {
            "review_requested": "BOOLEAN NOT NULL DEFAULT FALSE",
            "video_path": "TEXT",
            "audio_events": "TEXT NOT NULL DEFAULT 'null'",
            "audio_timeline": "TEXT NOT NULL DEFAULT 'null'",
            "severity_score": "INTEGER NOT NULL DEFAULT 0",
            "severity_factors": "TEXT NOT NULL DEFAULT '{}'",
            "text_issue_type": "TEXT",
            "detected_language": "TEXT",
            "location_context": "TEXT NOT NULL DEFAULT '[]'",
            "duplicate_cluster_id": "TEXT",
            "duplicate_count": "INTEGER NOT NULL DEFAULT 1",
            "visual_risk_factors": "TEXT NOT NULL DEFAULT '[]'",
            "text_analysis": "TEXT NOT NULL DEFAULT '{}'",
            "ward_id": "TEXT",
            "ward_name": "TEXT",
            "assigned_officer": "TEXT",
            "assigned_queue": "TEXT",
            "sla_hours": "DOUBLE PRECISION",
            "escalation_path": "TEXT NOT NULL DEFAULT '[]'",
            "routing_rule_id": "INTEGER",
            "reporter_label": "TEXT NOT NULL DEFAULT 'Anonymous'",
            "reporter_email": "TEXT",
            "reporter_phone": "TEXT",
            "notification_channels": "TEXT NOT NULL DEFAULT '[]'",
        }

        for name, declaration in missing_columns.items():
            if name not in columns:
                conn.execute(
                    f"ALTER TABLE tickets ADD COLUMN IF NOT EXISTS {name} {declaration}"
                )

        count = conn.execute(
            "SELECT COUNT(*) AS count FROM routing_rules"
        ).fetchone()["count"]

        if count == 0:
            try:
                sla_by_department = json.loads(
                    get_settings().sla_hours_json
                )
            except (json.JSONDecodeError, TypeError):
                sla_by_department = {}

            defaults = [
                ("pothole", "Roads"),
                ("water_leak", "Water"),
                ("garbage", "Sanitation"),
                ("streetlight", "Electrical"),
                ("bridge_crack", "Roads & Bridges"),
                ("other", "Triage desk"),
                ("not_civic", "Triage desk"),
            ]

            fallback_sla = {
                "Roads": 48,
                "Roads & Bridges": 24,
                "Water": 24,
                "Sanitation": 48,
                "Electrical": 24,
                "Triage desk": 72,
            }

            for issue, department in defaults:
                configured_sla = (
                    sla_by_department.get(department)
                    if isinstance(sla_by_department, dict)
                    else None
                )

                sla = float(
                    configured_sla
                    if configured_sla is not None
                    else fallback_sla[department]
                )

                conn.execute(
                    """
                    INSERT INTO routing_rules (
                        issue_type,
                        department,
                        queue,
                        sla_hours,
                        escalation_path,
                        priority,
                        created_at
                    )
                    VALUES (%s, %s, %s, %s, %s, %s, %s)
                    """,
                    (
                        issue,
                        department,
                        department,
                        sla,
                        dumps(["JE", "AE", "EE", "Commissioner"]),
                        100,
                        utc_now(),
                    ),
                )


def dumps(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False)


def row_dict(row: dict | None) -> dict[str, Any] | None:
    return dict(row) if row else None
